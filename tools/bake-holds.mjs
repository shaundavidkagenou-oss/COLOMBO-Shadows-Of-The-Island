// 73rd: bakes the weapon holds (GripSolver.solve: hand seated on the grip, fingers closed, trigger finger, support hand) for
// the three heroes × every gun into src/combat/holdsBaked.js, so switching weapons never solves one in play (0.1–0.2 s each).
// Keys: hand signature (finger bone offsets) | hold signature (the gun's hold description) — an edited gun or a different hand
// misses and is solved at run time as before (then remembered on that machine).   node tools/bake-holds.mjs
import './node-dom-stub.mjs';
import fs from 'node:fs';
const THREE = await import('three');
const { Character, HEROES } = await import('../src/actors/Character.js');
const { WEAPONS } = await import('../src/combat/WeaponDefs.js');
const { buildWeaponModel } = await import('../src/combat/WeaponModels.js');
const G = await import('../src/combat/GripSolver.js');
const out = {}; const t0 = performance.now(); const models = WEAPONS.map((w) => { const m = buildWeaponModel(w); m.updateMatrixWorld(true); return m; });
for (const id of ['dineth', 'shashika', 'david']) {
  const ch = new Character(HEROES[id]); const sc = new THREE.Scene(); sc.add(ch.root); ch.root.updateMatrixWorld(true); const hs = G.handSig(ch.bones);
  for (const m of models) { if (!m.userData.hold) continue; const key = hs + '|' + G.holdSig(m.userData.hold); if (out[key]) continue; out[key] = G.holdToPlain(G.solveHoldRaw(ch.bones, m.userData)); }
  console.log(id, hs, Object.keys(out).length, ((performance.now() - t0) / 1000).toFixed(1) + ' s');
}
// round trip check
const k0 = Object.keys(out)[0]; const back = G.holdToPlain(G.holdFromPlain(out[k0])); if (JSON.stringify(back) !== JSON.stringify(out[k0])) { console.error('round trip mismatch'); process.exit(1); }
const src = '// generated by tools/bake-holds.mjs — weapon holds for the three heroes × every gun (GripSolver.holdFor). Do not edit by hand.\nexport default ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(new URL('../src/combat/holdsBaked.js', import.meta.url), src); console.log('wrote', Object.keys(out).length, 'holds,', (src.length / 1024).toFixed(0), 'KB');
