// Bakes the Viharamahadevi Park Buddha statue (sculpted signed-distance form, src/world/BuddhaStatue.js) into
// src/world/buddhaData.js: near LOD (head 3 cm grid, body 4.5 cm), far LOD (9 cm). Run: node tools/bake-buddha.mjs
import fs from 'node:fs';
const B = await import('../src/world/BuddhaStatue.js');
const t0 = Date.now();
const hi = B.sculptBuddha(0.045, 0.03).map(B.encodeMesh);
const lo = B.sculptBuddha(0.095, 0).map(B.encodeMesh);
const out = `// GENERATED by tools/bake-buddha.mjs — do not edit by hand. Sculpted statue meshes (original work, see BuddhaStatue.js).\nexport default ${JSON.stringify({ hi, lo })};\n`;
fs.writeFileSync(new URL('../src/world/buddhaData.js', import.meta.url), out);
console.log('baked', (out.length / 1024).toFixed(0) + ' KB', 'in', Date.now() - t0, 'ms');
