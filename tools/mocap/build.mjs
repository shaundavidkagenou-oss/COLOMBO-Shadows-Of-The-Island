// Builds src/anim/mocapData.js from CMU Graphics Lab motion capture (mocap.cs.cmu.edu; BVH conversion by B. Hahne, mirrored
// at github.com/una-dinosauria/cmu-mocap). The CMU database is free for research and commercial use:
//   "The data used in this project was obtained from mocap.cs.cmu.edu. The database was created with funding from NSF EIA-0196217."
// Each clip is a trimmed segment of one real performance, retargeted onto the game rig (retarget.mjs), resampled at 30 fps and
// stored as 16-bit quaternions per bone per frame + the hip offset (mm). Looping clips get their tail cross-faded into the head.
//   node tools/mocap/build.mjs            (downloads the source BVH files into .cache/mocap on first run)
import fs from 'node:fs';
import path from 'node:path';
import * as THREE from 'three';
import { parseBVH } from './bvh.mjs';
import { retarget, GAME_BONES } from './retarget.mjs';

// name, source take (subject_trial), segment [a, b] in seconds of the 120 fps take, loop, hip anchor
export const DEFS = [
  { name: 'idle', take: '111_28', a: 0.6, b: 3.9, loop: true, note: 'standing still: weight shifts, breathing, small head moves' },
  { name: 'idle2', take: '40_10', a: 3.3, b: 6.8, loop: true, note: 'waiting for a bus: a glance at the watch, shifting weight' },
  { name: 'talk', take: '18_08', a: 9.6, b: 17.4, loop: true, note: 'conversation, explaining with hand gestures' },
  { name: 'argue', take: '80_48', a: 1.2, b: 8.6, loop: true, note: 'arguing' },
  { name: 'point', take: '80_48', a: 3.0, b: 4.9, note: 'emphatic forward jabs of the right hand (a demand)' },
  { name: 'shrug', take: '141_21', a: 0.3, b: 1.6, note: 'shrug' },
  { name: 'rise', take: '111_09', a: 2.6, b: 4.2, anchor: 'start', travel: 0.5, note: 'get up from a chair' },
];
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const CACHE = process.env.MOCAP_CACHE || path.join(ROOT, '.cache/mocap');

async function load(take) {
  const f = path.join(CACHE, take + '.bvh'); if (fs.existsSync(f)) return fs.readFileSync(f, 'utf8');
  fs.mkdirSync(CACHE, { recursive: true }); const dir = String(parseInt(take.split('_')[0], 10)).padStart(3, '0');
  const H = { 'User-Agent': 'colombo-mocap', Accept: 'application/vnd.github+json', ...(process.env.GITHUB_TOKEN ? { Authorization: 'Bearer ' + process.env.GITHUB_TOKEN } : {}) };
  const meta = await (await fetch(`https://api.github.com/repos/una-dinosauria/cmu-mocap/contents/data/${dir}/${take}.bvh`, { headers: H })).json();
  const blob = await (await fetch(`https://api.github.com/repos/una-dinosauria/cmu-mocap/git/blobs/${meta.sha}`, { headers: H })).json();
  const txt = Buffer.from(blob.content, 'base64').toString('utf8'); fs.writeFileSync(f, txt); return txt;
}

function crossfadeLoop(R, secs = 0.5) {
  const F = R.frames, K = Math.min(Math.round(secs * R.fps), Math.floor(F.length / 3)); const n = F.length; const out = [];
  for (let j = 0; j < n - K; j++) {
    if (j < n - 2 * K) { out.push(F[j + K]); continue; }
    const i = j - (n - 2 * K); const w = i / K; const a = F[n - K + i], b = F[i]; const s = w * w * (3 - 2 * w);
    const loc = {}; for (const g of GAME_BONES) loc[g] = a.loc[g].clone().slerp(b.loc[g], s);
    out.push({ loc, hip: a.hip.map((v, k) => v + (b.hip[k] - v) * s) });
  }
  R.frames = out; return R;
}

const b64 = (ta) => Buffer.from(ta.buffer, ta.byteOffset, ta.byteLength).toString('base64');
const clips = {}; let bytes = 0;
for (const d of DEFS) {
  const B = parseBVH(await load(d.take)); const f0 = Math.round(d.a / B.dt), f1 = Math.min(B.frames - 1, Math.round(d.b / B.dt));
  let R = retarget(B, f0, f1, 30, { mirror: !!d.mirror, travel: d.travel ?? 1 }); if (d.loop) R = crossfadeLoop(R);
  const F = R.frames, n = F.length, nb = GAME_BONES.length; const q = new Int16Array(n * nb * 4), h = new Int16Array(n * 3);
  const anchor = d.anchor === 'start' ? F[0].hip : null;
  for (let i = 0; i < n; i++) {
    GAME_BONES.forEach((g, k) => { const Q = F[i].loc[g].normalize(); const s = Q.w < 0 ? -1 : 1; const o = (i * nb + k) * 4; q[o] = Math.round(Q.x * s * 32767); q[o + 1] = Math.round(Q.y * s * 32767); q[o + 2] = Math.round(Q.z * s * 32767); q[o + 3] = Math.round(Q.w * s * 32767); });
    const hp = F[i].hip; h[i * 3] = Math.round((hp[0] - (anchor ? anchor[0] : 0)) * 1000); h[i * 3 + 1] = Math.round(hp[1] * 1000); h[i * 3 + 2] = Math.round((hp[2] - (anchor ? anchor[2] : 0)) * 1000);
  }
  clips[d.name] = { fps: 30, n, loop: !!d.loop, src: `CMU ${d.take} ${d.a}-${d.b}s`, q: b64(q), h: b64(h) }; bytes += q.byteLength + h.byteLength;
  console.log(d.name.padEnd(6), d.take.padEnd(7), n, 'frames', (n / 30).toFixed(2) + 's');
}
let js = `// GENERATED by tools/mocap/build.mjs — do not edit. Motion capture from the CMU Graphics Lab Motion Capture Database
// (mocap.cs.cmu.edu), free for research and commercial use: "The data used in this project was obtained from mocap.cs.cmu.edu.
// The database was created with funding from NSF EIA-0196217." Retargeted onto the game rig; see tools/mocap/retarget.mjs.
export const MOCAP_BONES = ${JSON.stringify(GAME_BONES)};
export const MOCAP_CLIPS = {\n`;
for (const [k, c] of Object.entries(clips)) js += `  ${k}: { fps: ${c.fps}, n: ${c.n}, loop: ${c.loop}, src: '${c.src}',\n    q: '${c.q}',\n    h: '${c.h}' },\n`;
js += '};\n';
fs.mkdirSync(path.join(ROOT, 'src/anim'), { recursive: true }); fs.writeFileSync(path.join(ROOT, 'src/anim/mocapData.js'), js);
console.log('wrote src/anim/mocapData.js', (js.length / 1024).toFixed(0) + ' KB', '(' + (bytes / 1024).toFixed(0) + ' KB raw)');
