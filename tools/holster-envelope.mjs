// 87th: bakes the universal holster's shape. Every pistol is built, its surface profile measured (CarryGear.weaponProfile)
// and the union of all of them (grip origin aligned, 5 mm bins along the bore) written to src/combat/holsterEnvelope.js,
// together with each pistol's seat in that holster (a small y offset that centres a smaller slide in the shell, and how far
// the muzzle reaches so the draw lifts it exactly clear of the mouth). One holster, one size, whatever pistol rides in it —
// it never changes shape when the selected pistol changes. Re-run after editing a pistol model:  node tools/holster-envelope.mjs
import './node-dom-stub.mjs';
import fs from 'node:fs';
const { WEAPONS } = await import('../src/combat/WeaponDefs.js');
const { buildWeaponModel } = await import('../src/combat/WeaponModels.js');
const { weaponProfile } = await import('../src/combat/CarryGear.js');

const bin = 0.005; const U = new Map(); const prof = []; let muzzleZ = 0;
for (let i = 0; i < WEAPONS.length; i++) {
  if (WEAPONS[i].cls !== 'pistol') continue; const m = buildWeaponModel(WEAPONS[i]); m.updateMatrixWorld(true); const pr = weaponProfile(m);
  if (Math.abs(pr.bin - bin) > 1e-9) throw new Error('profile bin changed');
  const mz = m.userData.muzzle ? m.userData.muzzle.z : pr.zMax; muzzleZ = Math.max(muzzleZ, mz); prof.push({ id: WEAPONS[i].id, pr, mz });
  const k0 = Math.round(pr.z0 / bin);
  for (let j = 0; j < pr.n; j++) { const k = k0 + j; let e = U.get(k); if (!e) U.set(k, (e = [Infinity, -Infinity, Infinity, -Infinity]));
    e[0] = Math.min(e[0], pr.y0[j]); e[1] = Math.max(e[1], pr.y1[j]); e[2] = Math.min(e[2], pr.x0[j]); e[3] = Math.max(e[3], pr.x1[j]); }
}
const keys = [...U.keys()].sort((a, b) => a - b); const k0 = keys[0], n = keys[keys.length - 1] - k0 + 1; const r4 = (v, up) => (up ? Math.ceil(v * 1e4) : Math.floor(v * 1e4)) / 1e4;
const env = { z0: k0 * bin, bin, n, y0: [], y1: [], x0: [], x1: [], muzzleZ: r4(muzzleZ, true) }; let last = U.get(k0);
for (let j = 0; j < n; j++) { const e = U.get(k0 + j) || last; last = e; env.y0.push(r4(e[0], false)); env.y1.push(r4(e[1], true)); env.x0.push(r4(e[2], false)); env.x1.push(r4(e[3], true)); }
env.zMin = env.z0; env.zMax = (k0 + n) * bin;
const eAt = (arr, z) => arr[Math.max(0, Math.min(n - 1, Math.floor((z - env.z0) / bin)))];
// seats: centre the slide / frame in the shell (frame region z 0 … 8 cm), clamped so nothing leaves the envelope
const seats = {};
for (const { id, pr, mz } of prof) {
  const pAt = (arr, z) => arr[Math.max(0, Math.min(pr.n - 1, Math.floor((z - pr.z0) / bin)))]; let s = 0, c = 0;
  for (let z = 0.0025; z < Math.min(0.08, mz); z += bin) { s += (eAt(env.y0, z) + eAt(env.y1, z) - pAt(pr.y0, z) - pAt(pr.y1, z)) / 2; c++; }
  let dy = c ? s / c : 0; let lo = -Infinity, hi = Infinity;
  for (let z = -0.03; z < mz; z += bin) { const ez = Math.max(z, 0.004); hi = Math.min(hi, eAt(env.y1, ez) - pAt(pr.y1, z)); if (z >= 0.004) lo = Math.max(lo, eAt(env.y0, z) - pAt(pr.y0, z)); }
  dy = Math.max(Math.min(dy, hi), Math.min(lo, 0)); seats[id] = { dy: Math.round(dy * 1e4) / 1e4, muzzleZ: Math.round(mz * 1e4) / 1e4 };
  console.log(id.padEnd(8), 'dy', (dy * 1000).toFixed(1), 'mm  muzzle', (mz * 1000).toFixed(0), 'mm');
}
const src = '// generated by tools/holster-envelope.mjs — the universal holster\'s pistol envelope (union of every pistol\'s profile, grip\n// origin aligned) and each pistol\'s seat in it. Do not edit by hand; re-run the tool after changing a pistol model.\n' +
  'export const PISTOL_ENVELOPE = ' + JSON.stringify(env) + ';\nexport const PISTOL_SEATS = ' + JSON.stringify(seats) + ';\n';
fs.writeFileSync(new URL('../src/combat/holsterEnvelope.js', import.meta.url), src);
console.log('envelope', n, 'bins, z', env.z0.toFixed(3), '…', env.zMax.toFixed(3), ' muzzle', env.muzzleZ);
